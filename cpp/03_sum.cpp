#include<iostream>
using namespace std;
int main(){
    int number1, number2;
    cout<<"Enter the value of number 1: ";
    cin>>number1;
    cout<<"Enter the value of number 2: ";
    cin>>number2;
    cout<<"The sum is: "<<number1+number2;
    return 0;
}

/* '>>' is the Extraction operator
'<<' is the Inseration operator
cin>> is used to read input from the user*/